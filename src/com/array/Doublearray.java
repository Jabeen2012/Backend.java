package com.array;

public class Doublearray {

	public static void main(String[] args) {
		// Double array using for loop
		double[] arr = new double[3];
				arr[0]=10.5;
				arr[1]=20.75;
				arr[2]=30.25;
				
				System.out.println("-----double array");
				for(int i=0; i<arr.length; i++) {
					System.out.println(arr[i]);
				}
		

	}

}
