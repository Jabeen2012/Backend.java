package com.array;

public class Booleanarray {

	public static void main(String[] args) {
		// boolean array using for loop
		boolean[] arr = new boolean[2];
		arr[0]=true;
		arr[1]=false;
		System.out.println("---- Boolean array");
		for(int i=0; i<arr.length; i++) {
			System.out.println(arr[i]);
		}

	}

}
