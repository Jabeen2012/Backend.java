package com.array;

public class Characterarray {

	public static void main(String[] args) {
		// character array using  for each loop
		char[] letters = new char[6];
		letters [0]='j';
		letters [1]='a';
		letters [2]='b';
		letters [3]='e';
		letters [4]='e';
		letters [5]='n';
		System.out.println("----character array--------");
		for(char ch : letters) {
			System.out.println(ch);
		}
			
		

	}

}
